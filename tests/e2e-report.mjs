// Renders the results table of docs/research/e2e-latency.md from the bench's raw JSON.
//
//   bun tests/bench-e2e.mjs --turns 50 --barge 10 --publish   # writes docs/research/e2e-latency.json
//   bun run bench:report                                       # rewrites the table in the doc
//   bun tests/e2e-report.mjs --check                           # exit 1 if the doc is stale
//   bun tests/e2e-report.mjs some-run.json                     # print a table for any run
//
// The table sits between the e2e-results markers in the doc; nothing else is touched.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dir, '..');
const argv = process.argv.slice(2);
const flags = new Set(argv.filter((a) => a.startsWith('--')));
const file = argv.find((a) => !a.startsWith('--')) ?? path.join(root, 'docs/research/e2e-latency.json');
const DOC = path.join(root, 'docs/research/e2e-latency.md');
const START = '<!-- e2e-results:start (generated by tests/e2e-report.mjs from e2e-latency.json; do not edit) -->';
const END = '<!-- e2e-results:end -->';

export function render(run) {
  const m = run.metrics_ms;
  const cell = (v) => (v === undefined || v === null ? '-' : String(v));
  const row = (name, s) => `| ${name} | ${cell(s?.n)} | ${cell(s?.p50)} | ${cell(s?.p95)} | ${cell(s?.p99)} | ${cell(s?.max)} |`;
  const lines = [
    `Commit \`${run.commit}\` (\`git describe --always --dirty\`), ${run.date.slice(0, 10)}, ${run.platform}, ` +
      `load average ${run.load_average?.join(' / ') ?? 'not recorded'}, rivetkit ${run.rivetkit}. ` +
      `${run.turns} measured turns and ${run.barge_ins} barge-ins after one warm-up turn` +
      `${run.speech_faked ? '' : '; speech not faked'}.`,
    '',
    '| Measure (ms) | n | p50 | p95 | p99 | max |',
    '| --- | --- | --- | --- | --- | --- |',
    row('submit → `turn.started`', m.submit_to_turn_started),
    row('submit → first `text.delta`', m.submit_to_first_text_delta),
    row('submit → first `speech.ready`', m.submit_to_first_speech_ready),
    row('submit → first PCM byte at the player', m.submit_to_first_pcm_byte),
    row('submit → `turn.completed`', m.submit_to_turn_completed),
    row('silence inside a reply (≥ 20 ms), per gap', m.silence_gap_within_reply),
    row('longest silence per turn', m.max_silence_per_turn),
    row('barge-in → player stopped', m.barge_in_to_audio_closed),
    row('barge-in → turn end event (`turn.cancelled`)', m.barge_in_to_turn_terminal_event),
    row('barge-in → model stream closed', m.barge_in_to_provider_stream_closed),
    row('(fake speech server fell behind, ≥ 20 ms)', run.fake_speech_fell_behind_ms),
    '',
  ];
  const checks = [`${run.failures?.length ?? 0} failed checks`, `${run.leaks?.length ?? 0} leaks`];
  if (run.audio) {
    checks.push(
      `${run.audio.turns_checked} turns played ${run.audio.observed_samples} of ${run.audio.expected_samples} samples the fake provider sent`,
      `${run.audio.barges_stopped} of ${run.barge_ins} barged players stopped`,
    );
  }
  const g = m.silence_gap_within_reply;
  checks.push(`${g.turns_with_gap ?? 0} turns with a silence, ${g.total_ms ?? 0} ms in total`);
  lines.push(
    `Checks: ${checks.join('; ')}. Server RSS ${Math.round(run.rss_kb.server.after_warmup / 1024)} → ` +
      `${Math.round(run.rss_kb.server.end / 1024)} MB (max ${Math.round(run.rss_kb.server.max / 1024)}), engine ` +
      `${Math.round(run.rss_kb.engine.after_warmup / 1024)} → ${Math.round(run.rss_kb.engine.end / 1024)} MB ` +
      `(max ${Math.round(run.rss_kb.engine.max / 1024)}). ${run.model_calls_per_turn.toFixed(2)} model calls and ` +
      `${run.speech_requests_per_turn?.toFixed(2) ?? '-'} speech requests per turn.`,
  );
  return lines.join('\n');
}

if (import.meta.main) {
  const run = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!run.metrics_ms) {
    console.error(`${file}: no metrics (the run failed before measuring)`);
    process.exit(1);
  }
  const table = render(run);
  if (!flags.has('--check') && !flags.has('--write')) {
    console.log(table);
    process.exit(0);
  }
  const doc = fs.readFileSync(DOC, 'utf8');
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) {
    console.error(`${DOC}: missing the e2e-results markers`);
    process.exit(1);
  }
  const next = `${doc.slice(0, a + START.length)}\n\n${table}\n\n${doc.slice(b)}`;
  if (flags.has('--check')) {
    if (next !== doc) {
      console.error(`${path.relative(root, DOC)} is stale; run bun run bench:report`);
      process.exit(1);
    }
    process.exit(0);
  }
  fs.writeFileSync(DOC, next);
  console.error(`wrote ${path.relative(root, DOC)} from ${path.relative(root, file)}`);
}
